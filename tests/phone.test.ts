import { describe, expect, it } from 'vitest'
import { parsePhone, trimTrunkDigit } from '@/lib/phone'

describe('parsePhone — один номер во всех привычных записях', () => {
  it.each([
    '+7 700 123 45 67',
    '+7 (700) 123-45-67',
    '+77001234567',
    '8 700 123 45 67',
    '87001234567',
    '7 700 123 45 67',
    '77001234567',
    '700 123 45 67',
    '7001234567',
    // Привычка зоны +7 — набирать «7» или «8» перед номером, даже когда
    // код страны уже стоит плюсом: trimTrunkDigit снимает лишнюю цифру.
    '+7 8 700 123 45 67',
    '+7 7 700 123 45 67',
  ])('«%s» → +77001234567', (input) => {
    expect(parsePhone(input)).toEqual({ ok: true, e164: '+77001234567' })
  })

  // Разбор больше не завязан на страну (DEFAULT_COUNTRY — только флаг поля),
  // а на код зоны +7: российский мобильный без плюса принимается наравне
  // с казахстанским.
  it.each([
    ['912 345 67 89', '+79123456789'],
    ['7 906 403 26 80', '+79064032680'],
    // Настоящий питерский городской с восьмёркой в начале — десять цифр
    // после +7, и trimTrunkDigit его не трогает (её правило — про одиннадцать).
    ['+7 812 345 67 89', '+78123456789'],
  ] as const)('российский «%s» → %s', (input, e164) => {
    expect(parsePhone(input)).toEqual({ ok: true, e164 })
  })

  // Решение владельца, пересмотренное им же: любая страна с плюсом
  // принимается, Казахстан — страна по умолчанию флага, а не ограничение.
  it.each([
    ['+996 555 112233', '+996555112233'],
    ['+1 202 555 0100', '+12025550100'],
  ] as const)('иностранный номер «%s» → %s', (input, e164) => {
    expect(parsePhone(input)).toEqual({ ok: true, e164 })
  })
})

describe('parsePhone — причина отказа', () => {
  it.each([
    ['', 'empty'],
    ['abc', 'empty'],
    ['+', 'empty'],
    ['7700123', 'short'],
    // Недобранный номер с местной восьмёрки: справочник не стрипает её
    // как трунк-префикс на невалидном разборе, а наш код досчитывает сам —
    // «8 и восемь цифр», а не городской код 8xx (настоящий 8xx справочник
    // признал бы валидным в блоке выше).
    ['8 700 123 45 6', 'short'],
    ['+7 870 012 34 56', 'short'],
    ['770012345678', 'long'],
    ['+7 7001 234 56 78', 'long'],
    ['+7 700 123 45 678', 'long'],
    ['+7 000 000 00 00', 'format'],
    // Один код страны без единой цифры номера: parsePhoneNumberFromString
    // не возвращает объект вовсе — это не «short», а «никакой».
    ['+7', 'format'],
    // 11 цифр без кода страны и без местной восьмёрки — не стрипаются как
    // трунк-префикс (стрип только для ровно десяти цифр с восьмёрки),
    // и весь кусок на цифру длиннее положенных десяти зоны +7.
    ['91234567890', 'long'],
  ] as const)('«%s» → %s', (input, reason) => {
    expect(parsePhone(input)).toEqual({ ok: false, reason })
  })
})

describe('trimTrunkDigit — лишняя ведущая цифра зоны +7', () => {
  it.each([
    ['+787001234567', '+77001234567'],
    ['+777001234567', '+77001234567'],
    // Без первой цифры номер не настоящий — оставляем как есть, пусть
    // ошибка скажет «лишние».
    ['+770012345678', '+770012345678'],
    // Десять цифр после +7 — уже настоящий номер (питерский городской
    // с 8 в начале), правило про одиннадцать цифр его не касается.
    ['+78123456789', '+78123456789'],
    ['+77001234567', '+77001234567'],
  ] as const)('«%s» → «%s»', (input, expected) => {
    expect(trimTrunkDigit(input)).toBe(expected)
  })
})

import { describe, expect, it } from 'vitest'
import { parsePhone } from '@/lib/phone'

describe('parsePhone — один номер во всех привычных записях', () => {
  it.each([
    '+7 700 123 45 67',
    '+7 (700) 123-45-67',
    '+77001234567',
    '8 700 123 45 67',
    '87001234567',
    '7 700 123 45 67',
    '77001234567',
    '700 123 45 67',
    '7001234567',
  ])('«%s» → +77001234567', (input) => {
    expect(parsePhone(input)).toEqual({ ok: true, e164: '+77001234567' })
  })

  // Зона +7 общая с Россией: мобильный без восьмёрки — те же 10 цифр.
  it('российский мобильный без восьмёрки', () => {
    expect(parsePhone('912 345 67 89')).toEqual({ ok: true, e164: '+79123456789' })
  })

  // Решение владельца, пересмотренное им же: любая страна с плюсом — не только +7.
  it.each([
    ['+996 555 112233', '+996555112233'],
    ['+1 202 555 0100', '+12025550100'],
  ] as const)('иностранный номер «%s» → %s', (input, e164) => {
    expect(parsePhone(input)).toEqual({ ok: true, e164 })
  })
})

describe('parsePhone — причина отказа', () => {
  it.each([
    ['', 'empty'],
    ['abc', 'empty'],
    ['+', 'empty'],
    ['7700123', 'short'],
    ['+7', 'short'],
    // Не «8 700 123 45 6»: у него ровно 10 цифр, и справочник читает их как
    // валидный российский номер (isValid: true) — короче на одну цифру,
    // и это уже точно недобранный местный номер.
    ['8 700 123 45', 'short'],
    // Одна лишняя цифра — не TOO_LONG: у справочника это «неизвестная длина»
    // для всех стран зоны +7, что parsePhone возвращает как format, а не long.
    ['770012345678', 'format'],
    ['+7 7001 234 56 78', 'format'],
    // Настоящий TOO_LONG справочник даёт только на числах, невозможных ни для
    // одной страны в принципе — небольшой перебор цифр этого не вызывает.
    ['700123456789012345', 'long'],
    // 11 цифр, но не с 7 и не с 8 — длина не подходит ни одной стране зоны +7.
    ['91234567890', 'format'],
    ['+7 000 000 00 00', 'format'],
  ] as const)('«%s» → %s', (input, reason) => {
    expect(parsePhone(input)).toEqual({ ok: false, reason })
  })
})

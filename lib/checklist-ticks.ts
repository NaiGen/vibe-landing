/**
 * Галочки чек-листа первого экрана: «я это собрал». Живут в браузере
 * посетителя и на сайт не влияют — это пометка для себя, а не данные
 * проекта. Бэкенда для них нет намеренно: чек-лист виден на статике
 * в Vercel раньше, чем ученик открывает редактор.
 *
 * Здесь нет ни одного импорта из node: модуль забирает клиентский
 * компонент, и node-модуль в его сборке всё бы уронил.
 *
 * Каждое обращение к хранилищу — в try/catch. `localStorage` бросает
 * на самом доступе к свойству в приватном окне Safari и при выключенных
 * данных сайтов, а на сервере его нет вовсе.
 */
const KEY = 'landing:checklist'

export type Ticks = Record<string, boolean>

export function readTicks(): Ticks {
  try {
    const raw = globalThis.localStorage?.getItem(KEY)
    if (!raw) return {}
    const parsed: unknown = JSON.parse(raw)
    if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) return {}
    return Object.fromEntries(Object.entries(parsed).map(([id, on]) => [id, on === true]))
  } catch {
    return {}
  }
}

/**
 * Записывает галочки, СЛИВАЯ их с тем, что уже лежит в хранилище, —
 * и это главное здесь, а не сохранение как таковое.
 *
 * Чек-лист рендерится двумя экземплярами списка: «собрать сейчас»
 * и «перед запуском». У каждого своя копия состояния, снятая при
 * монтировании, и запись «весь объект целиком» стирала чужие галочки:
 * кто нажал последним, тот и переписал. Слияние в момент записи делает
 * единственным источником правды само хранилище — экземпляров может быть
 * сколько угодно, и ни один не отвечает за чужие ключи.
 *
 * Выбрано это, а не общее состояние на панели: панель — серверный
 * компонент, состояния в ней не завести без ещё одной клиентской обёртки
 * вокруг обоих списков. Ключ по-прежнему один, поэтому набор галочек
 * видно и чистится одной строкой в инструментах разработчика.
 *
 * Снятую галочку слияние не теряет: `false` — такое же значение, как
 * `true`, и оно перекрывает лежащее.
 */
export function writeTicks(ticks: Ticks): void {
  try {
    globalThis.localStorage?.setItem(KEY, JSON.stringify({ ...readTicks(), ...ticks }))
  } catch {
    // Хранилище недоступно — галочка просто не переживёт перезагрузку.
    // Ронять из-за этого страницу нечего: чек-лист читается и без неё.
  }
}
